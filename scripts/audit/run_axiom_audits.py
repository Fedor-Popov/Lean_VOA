_DEPENDENCY_HEADER = re.compile(r"^'(.+)' depends on axioms: \[(.*)$")


def parse_axiom_reports(output: str) -> list[AxiomReport]:
    """Parse only Lean's possibly multiline `#print axioms` dependency lines."""
    reports: list[AxiomReport] = []
    lines = output.splitlines()
    line_index = 0

    while line_index < len(lines):
        empty = re.fullmatch(r"'(.+)' does not depend on any axioms", lines[line_index])
        if empty is not None:
            reports.append(AxiomReport(empty.group(1), ()))
            line_index += 1
            continue
        header = _DEPENDENCY_HEADER.match(lines[line_index])
        if header is None:
            line_index += 1
            continue

        start_line = line_index + 1
        declaration = header.group(1)
        remainder = header.group(2)
        body_parts: list[str] = []
        while True:
            closing_bracket = remainder.find("]")
            if closing_bracket != -1:
                if remainder[closing_bracket + 1 :].strip():
                    raise AxiomOutputError(
                        f"line {line_index + 1}: non-whitespace after axiom list"
                    )
                body_parts.append(remainder[:closing_bracket])
                break
            body_parts.append(remainder)
            line_index += 1
            if line_index >= len(lines):
                raise AxiomOutputError(
                    f"line {start_line}: unclosed axiom list for '{declaration}'"
                )
            remainder = lines[line_index]

        body = " ".join(body_parts).strip()
        axioms = () if not body else tuple(item.strip() for item in body.split(","))
        if any(not axiom for axiom in axioms):
            raise AxiomOutputError(
                f"line {start_line}: empty axiom name for '{declaration}'"
            )
        reports.append(AxiomReport(declaration, axioms))
        line_index += 1

    return reports


def _canonical_axiom(axiom: str) -> str:
    # Namespace display depends on where the `#print axioms` command occurs.
    if axiom == "VOA.pbw":
        return "pbw"
    return axiom


def _format_axioms(axioms: set[str] | frozenset[str]) -> str:
    return "[" + ", ".join(sorted(axioms)) + "]"


def validate_reports(probe: Probe, reports: list[AxiomReport]) -> list[str]:
    """Validate exact declaration coverage and exact axiom sets for one probe."""
    errors: list[str] = []
    expected = set(probe.declarations)
    counts = Counter(report.declaration for report in reports)

    for declaration in sorted(counts.keys() - expected):
        errors.append(
            f"unexpected dependency report for '{declaration}' "
            f"({counts[declaration]} occurrence(s))"
        )

    by_declaration: dict[str, list[AxiomReport]] = {}
    for report in reports:
        by_declaration.setdefault(report.declaration, []).append(report)

    for declaration in probe.declarations:
        matching = by_declaration.get(declaration, [])
        if not matching:
            errors.append(f"missing dependency report for '{declaration}'")
            continue
        if len(matching) != 1:
            errors.append(
                f"dependency report for '{declaration}' appeared "
                f"{len(matching)} times (expected exactly once)"
            )
            continue

        canonical = tuple(_canonical_axiom(axiom) for axiom in matching[0].axioms)
        if len(canonical) != len(set(canonical)):
            errors.append(f"duplicate axiom in report for '{declaration}'")
            continue

        actual_axioms = set(canonical)
        expected_axioms = EXACT_AXIOM_OVERRIDES.get(
            declaration, PBW_AXIOMS if declaration == PBW_DECLARATION else BASE_AXIOMS
        )
        if actual_axioms != expected_axioms:
            errors.append(
                f"'{declaration}' has {_format_axioms(actual_axioms)}; expected "
                f"{_format_axioms(expected_axioms)}"
            )

    return errors


def _output_tail(output: str, line_count: int = 30) -> str:
    lines = output.rstrip().splitlines()
    return "\n".join(lines[-line_count:])


def execute_probe(probe: Probe) -> tuple[list[str], int]:
    """Run and validate one Lean probe, returning errors and report count."""
    try:
        completed = subprocess.run(
            probe.command,
            cwd=REPOSITORY_ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            encoding="utf-8",
            check=False,
            timeout=PROBE_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired:
        return [f"Lean exceeded the {PROBE_TIMEOUT_SECONDS}-second timeout"], 0
    except OSError as error:
        return [f"could not execute {' '.join(probe.command)}: {error}"], 0

    output = completed.stdout
    if completed.stderr:
        output += ("\n" if output else "") + completed.stderr
    if completed.returncode != 0:
        errors = [f"Lean exited with status {completed.returncode}"]
        tail = _output_tail(output)
        if tail:
            errors.append(f"Lean output (last 30 lines):\n{tail}")
        return errors, 0

    try:
        reports = parse_axiom_reports(output)
    except AxiomOutputError as error:
        return [f"malformed Lean axiom output: {error}"], 0
    return validate_reports(probe, reports), len(reports)


def main() -> int:
    total_reports = 0
    failed = False

    for probe in PROBES:
        errors, report_count = execute_probe(probe)
        total_reports += report_count
        if errors:
            failed = True
            print(f"FAIL {probe.name}:", file=sys.stderr)
            for error in errors:
                print(f"  {error}", file=sys.stderr)
        else:
            print(
                f"PASS {probe.name}: {report_count} declarations match the trust boundary"
            )

    if failed:
        print("Axiom audit enforcement failed.", file=sys.stderr)
        return 1

    print(
        f"Axiom audit enforcement passed: {total_reports} reports across "
        f"{len(PROBES)} probes."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
