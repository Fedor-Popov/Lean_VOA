    name: str
    filename: str
    declarations: tuple[str, ...]
    lean_options: tuple[str, ...] = ()

    @property
    def command(self) -> tuple[str, ...]:
        return (
            "lake",
            "env",
            "lean",
            *self.lean_options,
            f"scripts/audit/{self.filename}",
        )


